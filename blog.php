                            <span class="article-category">Строительство</span>
                            <h2>Электромонтажные работы: полный гайд для собственника</h2>
                            <p class="article-meta">10 ноября 2025 | Игорь Сорокин</p>
                            <p class="article-excerpt">Разбираемся, какие работы входят в электромонтаж, какие требуют лицензирования и как не допустить ошибок при выборе электрика...</p>
                            
                            <div class="article-full" style="display: none;">
                                <h3>Что входит в электромонтажные работы?</h3>
                                <p>Электромонтаж включает: проектирование сети, укладку кабелей, установку распределительных щитов, подключение розеток и выключателей, установку светильников, подключение силовых потребителей. Каждый из этих этапов требует профессиональной квалификации. Неправильный монтаж может привести к пожарам и поражению электротоком. Качество электромонтажных работ напрямую влияет на безопасность и долговечность всех электрических устройств в доме.</p>

                                <h3>Нормативы и требования</h3>
                                <p>Все работы должны проводиться в соответствии с ПУЭ (Правила устройства электроустановок) и ГОСТОМ. Электрик должен иметь допуск к работам с напряжением выше 380В. Обязательно проведение проверки сети специалистом, протоколирование результатов. Все это необходимо для получения акта и допуска к подключению от энергоснабжающей организации. Несоответствие нормативам может привести к отказу в подключении.</p>

                                <h3>Частые ошибки</h3>
                                <p>Самая частая ошибка — экономия на качестве кабеля и автоматики. Это приводит к коротким замыканиям и возгораниям. Используйте оборудование проверенных производителей — ABB, Legrand, Siemens. Не экономьте на автоматических выключателях и УЗО — это ваша безопасность и защита от поражения. Еще одна распространенная ошибка — несоответствие сечения кабеля нагрузке.</p>

                                <h3>Выбор электрика</h3>
                                <p>Требуйте документы о квалификации и лицензиях. Серьезные специалисты работают через компании с лицензией. Не берите электричество «в черную» даже если будет скидка — это опасно и незаконно. Требуйте гарантию на работы (минимум 2 года) и протоколы испытаний. Свяжитесь с энергоснабжающей компанией — они подскажут, какие компании имеют допуск на работы.</p>
