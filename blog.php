                                <p>Границы между гостиной, кухней и столовой стираются. Открытые планировки позволяют максимально использовать пространство и свет, создают ощущение простора. Но при этом нужна хорошая вентиляция и звукоизоляция. Такие решения особенно популярны в скандинавском и лофт-стилях. Тренд — мобильная мебель, которая позволяет легко переконфигурировать пространство.</p>

                                <h3>3. Натуральные материалы</h3>
                                <p>Дерево, камень, кирпич, бетон — натуральные материалы в тренде. Но не в «деревенском» стиле, а в современной интерпретации. Комбинация фактур создает визуальный интерес. Экологичность становится главным критерием при выборе отделки. Люди все больше стремятся использовать возобновляемые и биоразлагаемые материалы в своих домах.</p>

