</ul>
<p>Скользящее крепление — не «перестраховка»: деревянная стропильная система и железобетонный пояс по-разному реагируют на температуру и влажность. Жёсткое защемление в этом узле приводит к смятию древесины и появлению щелей в примыкании кровли к стене.</p>
<h2>Узел 2. Конёк: вентиляция или ловушка для влаги</h2>
<p>Конёк — место, где сходятся два ската и где чаще всего прекращается вентзазор. Если подконьковая зона закрыта наглухо, влага из утеплителя не уходит, и обрешётка начинает работать как губка.</p>
<ol>
<li>Вентзазор 40–50 мм сохраняется непрерывно от карниза до конька.</li>
<li>Выход воздуха — либо через коньковый аэратор, либо через щелевой продух под коньковой планкой.</li>
<li>Диффузионная мембрана должна иметь провис 10–15 мм между стропилами, иначе она натягивается и перестаёт отводить конденсат.</li>
</ol>
