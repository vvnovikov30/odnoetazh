<h2>Узел 1. Опирание на мауэрлат</h2>
<p>Мауэрлат — не «брус под стропила», а распределяющая балка. Если стропило опирается на стену через короткую подкладку, точечная нагрузка раздавливает газобетон или выдавливает кирпичную кладку.</p>
