<h2>Узел 3. Карнизный свес и капельник</h2>
<p>Свес — самый холодный участок крыши и одновременно место, куда стекает вся вода со ската. Здесь складываются три ошибки:</p>
<ul>
<li><strong>Капельник заведён под мембрану, а не поверх</strong> — вода уходит в утеплитель по краю.</li>
<li><strong>Лобовая доска вставлена без зазора</strong> — воздух не может войти в вентзазор, и конденсат остаётся в пироге.</li>
<li><strong>Желоб закреплён с уклоном в обратную сторону</strong> — вода стоит в желобе и зимой разрывает его льдом.</li>
</ul>
<p>Правильная последовательность слоёв на свесе: стропило → контробрешётка → мембрана с выпуском на капельник → капельник → крюк желоба, закреплённый <em>до</em> укладки покрытия.</p>
<h2>Чек-лист приёмки стропильной системы</h2>
<p>Проверяйте до монтажа покрытия — потом любая переделка стоит как треть крыши:</p>
<ol>
<li>Шаг стропил совпадает с проектом с допуском ±20 мм, а не «как получилось».</li>
<li>Все врубки и подрезки обработаны антисептиком, а не только торцы.</li>
<li>Между стропилом и мауэрлатом нет зазоров: щель более 3 мм — смятие и скрип.</li>
<li>Мембрана имеет провис и не порвана в местах прохода крепежа.</li>
<li>Контробрешётка идёт вдоль стропил и обеспечивает непрерывный вентзазор.</li>
<li>Капельник выведен поверх мембраны и не «утоплен» в лобовую доску.</li>
</ol>
<h2>Что это даёт на практике</h2>
<p>Инженерный разбор узла — это не про «правильную марку бруса», а про последовательность решений. Шаг стропил определяется пирогом и нагрузкой, сечение — нормируемым прогибом, а долговечность — тремя узлами: опиранием, коньком и свесом. Если хотя бы один из них собран по принципу «и так сойдёт», остальные уже не спасут.</p>
