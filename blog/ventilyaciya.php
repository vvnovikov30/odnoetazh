<li>В то же время в контрольной группе, дышавшей обычным ионизированным воздухом, крысы оставались здоровыми и активными</li>
</ul>
<p>Этот эксперимент доказал: <strong>млекопитающие не могут долго жить в деионизированном («мёртвом») воздухе, даже если он идеально чист химически</strong>.</p>
